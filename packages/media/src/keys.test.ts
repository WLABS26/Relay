import { describe, expect, it } from 'vitest';
import { assetOriginalKey, assetVariantKey, workspaceOfKey } from './keys';

const WS = '0193f2a0-0000-7000-8000-000000000001';
const ASSET = '0193f2a0-0000-7000-8000-0000000000aa';

describe('object keys', () => {
  it('are generated by the server, scoped by workspace, asset and version', () => {
    expect(assetOriginalKey(WS, ASSET, 1, 'mp4')).toBe(`ws/${WS}/assets/${ASSET}/v1/original.mp4`);
    expect(assetVariantKey(WS, ASSET, 2, 'thumbnail', 'jpg-640', 'jpg')).toBe(
      `ws/${WS}/assets/${ASSET}/v2/variants/thumbnail-jpg-640.jpg`,
    );
  });

  it('never let client-supplied pieces shape the path', () => {
    expect(() => assetOriginalKey('../other', ASSET, 1, 'mp4')).toThrow();
    expect(() => assetOriginalKey(WS, `${ASSET}/../x`, 1, 'mp4')).toThrow();
    expect(() => assetOriginalKey(WS, ASSET, 0, 'mp4')).toThrow();
    expect(assetOriginalKey(WS, ASSET, 1, '../../etc')).toMatch(/original\.bin$/);
    expect(() => assetVariantKey(WS, ASSET, 1, 'proxy', 'a/b', 'mp4')).toThrow();
    expect(() => assetVariantKey('../other', ASSET, 1, 'proxy', 'mp4-720', 'mp4')).toThrow();
    expect(() => assetVariantKey(WS, ASSET, 1.5, 'proxy', 'mp4-720', 'mp4')).toThrow();
  });

  it('maps a key back to its workspace for authorisation', () => {
    expect(workspaceOfKey(assetOriginalKey(WS, ASSET, 1, 'png'))).toBe(WS);
    expect(workspaceOfKey(`tmp/${WS}/x`)).toBeNull();
    expect(workspaceOfKey('ws/not-a-uuid-at-all-but-36-chars-long/x')).toBeNull();
  });
});
